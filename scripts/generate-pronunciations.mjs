#!/usr/bin/env node
// Generates a pronunciation clip (public/audio/vi/<slug>.m4a) for every Vietnamese phrase that has a speaker button,
// then rewrites components/speak/recordings.ts so the site plays those files.
//
//   npm run audio              make the clips that are missing
//   npm run audio -- --force   remake every clip
//
// Needs macOS: it uses the built-in Vietnamese voice (Linh) through `say`, and `afconvert` to make AAC .m4a files.
// A clip you have replaced with a recording of a real speaker (same file name) is left alone unless you pass --force.
// To use a different voice, e.g. a cloud text-to-speech service, replace synthesize() below; nothing else changes.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { slugify } from "../components/speak/slug.ts";
import { teas } from "../components/leaves/teas.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const outDir = join(root, "public/audio/vi");
const manifest = join(root, "components/speak/recordings.ts");
const force = process.argv.includes("--force");

const VOICE = "Linh";
const WORDS_PER_MINUTE = 140; // a little slower than conversation, for learners

// Keep in step with the <Speak text="…" /> buttons on the page; a button whose phrase is missing here still works,
// it just falls back to the device's own voice.
const phrases = [
  ...teas.map((t) => t.vi),
  // the six manners
  "Mời trà",
  "Tráng trà",
  "Rót đều",
  "Tam long giá ngọc",
  "Xem, ngửi, phẩm",
  "Trà đầu xuân",
  // the brewing gestures
  "Ngọc diệp hồi cung",
  "Cao sơn trường thủy",
  "Hạ sơn nhập thủy",
  // the proverb in the hero, and the greeting
  "Nhất thủy, nhì trà, tam bôi, tứ bình, ngũ quần anh",
  "Mời trà!",
];

function synthesize(text, file) {
  const tmp = mkdtempSync(join(tmpdir(), "tra-say-"));
  try {
    const aiff = join(tmp, "clip.aiff");
    execFileSync("say", ["-v", VOICE, "-r", String(WORDS_PER_MINUTE), "-o", aiff, text]);
    execFileSync("afconvert", ["-f", "m4af", "-d", "aac", "-b", "64000", "-c", "1", aiff, file]);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

mkdirSync(outDir, { recursive: true });
const seen = new Set();
for (const text of phrases) {
  const slug = slugify(text);
  if (seen.has(slug)) continue;
  seen.add(slug);
  const file = join(outDir, `${slug}.m4a`);
  if (existsSync(file) && !force) {
    console.log(`keep  ${slug}.m4a`);
    continue;
  }
  synthesize(text, file);
  console.log(`made  ${slug}.m4a  ← ${text}`);
}

const slugs = readdirSync(outDir)
  .filter((f) => f.endsWith(".m4a"))
  .map((f) => f.slice(0, -4))
  .sort();
writeFileSync(
  manifest,
  `// Generated by scripts/generate-pronunciations.mjs (npm run audio) — do not edit by hand.
// The clips in public/audio/vi/<slug>.m4a. A phrase listed here is played from its file on every device; any other
// phrase falls back to the browser's own Vietnamese voice, and its speaker button stays hidden if the device has none.
import { slugify } from "./slug";

export { slugify };

export const recorded = new Set<string>([
${slugs.map((s) => `  "${s}",`).join("\n")}
]);
`,
);
console.log(`\n${slugs.length} clips listed in components/speak/recordings.ts`);
